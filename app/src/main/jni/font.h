// Renderiza texto numa surface RGBA (bytes R,G,B,A; linha 0 = topo).
// (px,py) = canto superior esquerdo; scale = tamanho do "pixel".
inline void DrawText5x7(uint8_t* surface, int surface_w, int surface_h, int px,
                        int py, const char* text, int scale, uint8_t r,
                        uint8_t g, uint8_t b, uint8_t a = 255) {
  int cursor_x = px;
  for (const char* p = text; *p != '\0'; ++p) {
    const uint8_t* glyph = Font5x7Glyph(*p);
    if (glyph != nullptr) {
      for (int row = 0; row < 7; ++row) {
        const uint8_t bits = glyph[row];
        for (int col = 0; col < 5; ++col) {
          if ((bits & (0x10 >> col)) == 0) continue;
          for (int sy = 0; sy < scale; ++sy) {
            const int y = py + row * scale + sy;
            if (y < 0 || y >= surface_h) continue;
            for (int sx = 0; sx < scale; ++sx) {
              const int x = cursor_x + col * scale + sx;
              if (x < 0 || x >= surface_w) continue;
              uint8_t* pixel = surface + (y * surface_w + x) * 4;
              pixel[0] = r;
              pixel[1] = g;
              pixel[2] = b;
              pixel[3] = a;
            }
          }
        }
      }
    }
    cursor_x += 6 * scale;  // 5 colunas + 1 de espaco
  }
}

// Largura de um texto em pixels.
inline int TextWidth5x7(const char* text, int scale) {
  return static_cast<int>(strlen(text)) * 6 * scale;
}

